use aes::cipher::{BlockDecrypt, KeyInit};
use aes::Aes128;
use std::collections::HashMap;
use std::fs::File;
use std::io::{BufRead, BufReader};
use std::path::{Path, PathBuf};

#[derive(Debug, Clone, Default)]
pub struct KeySet {
    pub keys: HashMap<String, Vec<u8>>,
    pub title_keys: HashMap<String, [u8; 16]>,
    pub raw_ticket_keys: HashMap<String, ([u8; 16], u8)>,
    pub prod_keys_file: Option<PathBuf>,
    pub title_keys_file: Option<PathBuf>,
}

impl KeySet {
    pub fn auto_load() -> Self {
        Self::new()
    }

    pub fn new() -> Self {
        let mut ks = Self::default();
        ks.load_keys(None, None);
        ks
    }

    pub fn with_paths(prod_keys_path: Option<&Path>, title_keys_path: Option<&Path>) -> Self {
        let mut ks = Self::default();
        ks.load_keys(prod_keys_path, title_keys_path);
        ks
    }

    pub fn standard_search_paths() -> Vec<PathBuf> {
        let mut paths = Vec::new();

        if let Ok(appdata) = std::env::var("APPDATA") {
            let appdata_path = PathBuf::from(appdata);
            paths.push(appdata_path.join("yuzu").join("keys").join("prod.keys"));
            paths.push(appdata_path.join("Ryujinx").join("system").join("prod.keys"));
        }

        if let Ok(userprofile) = std::env::var("USERPROFILE") {
            paths.push(PathBuf::from(userprofile).join(".switch").join("prod.keys"));
        }

        paths.push(PathBuf::from("prod.keys"));
        paths.push(PathBuf::from("keys.txt"));
        paths.push(PathBuf::from("keys.dat"));
        paths
    }

    pub fn standard_title_keys_paths() -> Vec<PathBuf> {
        let mut paths = Vec::new();

        if let Ok(appdata) = std::env::var("APPDATA") {
            let appdata_path = PathBuf::from(appdata);
            paths.push(appdata_path.join("yuzu").join("keys").join("title.keys"));
            paths.push(appdata_path.join("Ryujinx").join("system").join("title.keys"));
        }

        if let Ok(userprofile) = std::env::var("USERPROFILE") {
            paths.push(PathBuf::from(userprofile).join(".switch").join("title.keys"));
        }

        paths.push(PathBuf::from("title.keys"));
        paths.push(PathBuf::from("title.keys_autogenerated"));
        paths
    }

    pub fn load_keys(&mut self, prod_keys_path: Option<&Path>, title_keys_path: Option<&Path>) {
        let mut target_prod = None;
        if let Some(p) = prod_keys_path
            && p.is_file() {
                target_prod = Some(p.to_path_buf());
            }
        if target_prod.is_none() {
            for p in Self::standard_search_paths() {
                if p.is_file() {
                    target_prod = Some(p);
                    break;
                }
            }
        }

        if let Some(p) = target_prod {
            self.parse_prod_keys(&p);
            self.prod_keys_file = Some(p);
        }

        let mut target_title = None;
        if let Some(p) = title_keys_path
            && p.is_file() {
                target_title = Some(p.to_path_buf());
            }
        if target_title.is_none() {
            for p in Self::standard_title_keys_paths() {
                if p.is_file() {
                    target_title = Some(p);
                    break;
                }
            }
        }

        if let Some(p) = target_title {
            self.parse_title_keys(&p);
            self.title_keys_file = Some(p);
        }
    }

    fn parse_prod_keys(&mut self, path: &Path) {
        if let Ok(file) = File::open(path) {
            let reader = BufReader::new(file);
            for line in reader.lines().map_while(std::result::Result::ok) {
                let trimmed = line.trim();
                if trimmed.is_empty() || trimmed.starts_with('#') || trimmed.starts_with(';') {
                    continue;
                }
                if let Some((k, v)) = trimmed.split_once('=') {
                    let key_name = k.trim().to_lowercase();
                    let hex_val: String = v.chars().filter(|c| c.is_ascii_hexdigit()).collect();
                    if let Ok(bytes) = hex::decode(&hex_val) {
                        self.keys.insert(key_name, bytes);
                    }
                }
            }
        }
    }

    fn parse_title_keys(&mut self, path: &Path) {
        if let Ok(file) = File::open(path) {
            let reader = BufReader::new(file);
            for line in reader.lines().map_while(std::result::Result::ok) {
                let trimmed = line.trim();
                if trimmed.is_empty() || trimmed.starts_with('#') || trimmed.starts_with(';') {
                    continue;
                }
                if let Some((k, v)) = trimmed.split_once('=') {
                    let rid = k.trim().to_lowercase();
                    let hex_val: String = v.chars().filter(|c| c.is_ascii_hexdigit()).collect();
                    if let Ok(bytes) = hex::decode(&hex_val)
                        && bytes.len() == 16 {
                            let mut key_arr = [0u8; 16];
                            key_arr.copy_from_slice(&bytes);
                            self.title_keys.insert(rid, key_arr);
                        }
                }
            }
        }
    }

    pub fn has_header_key(&self) -> bool {
        self.keys
            .get("header_key")
            .map(|k| k.len() == 32)
            .unwrap_or(false)
    }

    pub fn count(&self) -> usize {
        self.keys.len()
    }

    pub fn get_header_key(&self) -> Option<[u8; 32]> {
        self.keys.get("header_key").and_then(|k| {
            if k.len() == 32 {
                let mut arr = [0u8; 32];
                arr.copy_from_slice(k);
                Some(arr)
            } else {
                None
            }
        })
    }

    pub fn get_key_area_key(&self, key_type: &str, generation: usize) -> Option<[u8; 16]> {
        let name = format!("key_area_key_{key_type}_{generation:02x}");
        self.keys.get(&name).and_then(|k| {
            if k.len() == 16 {
                let mut arr = [0u8; 16];
                arr.copy_from_slice(k);
                Some(arr)
            } else {
                None
            }
        })
    }

    pub fn decrypt_key_area(&self, encrypted_keys: &[u8], generation: usize, key_type: &str) -> Vec<[u8; 16]> {
        if encrypted_keys.len() < 64 {
            return vec![[0u8; 16]; 4];
        }

        let kaek = match self.get_key_area_key(key_type, generation) {
            Some(k) => k,
            None => return vec![[0u8; 16]; 4],
        };

        let cipher = match Aes128::new_from_slice(&kaek) {
            Ok(c) => c,
            Err(_) => return vec![[0u8; 16]; 4],
        };

        let mut decrypted = Vec::with_capacity(4);
        for i in 0..4 {
            let mut block = [0u8; 16];
            block.copy_from_slice(&encrypted_keys[i * 16..(i + 1) * 16]);
            let mut generic_block = *aes::Block::from_slice(&block);
            cipher.decrypt_block(&mut generic_block);
            let mut out = [0u8; 16];
            out.copy_from_slice(&generic_block);
            decrypted.push(out);
        }

        decrypted
    }

    pub fn get_title_key(&self, rights_id: &[u8; 16], nca_key_gen: Option<usize>) -> Option<[u8; 16]> {
        let rid_hex = hex::encode(rights_id).to_lowercase();

        // 1. External title.keys takes precedence
        if let Some(k) = self.title_keys.get(&rid_hex) {
            return Some(*k);
        }

        // 2. Encrypted ticket title key
        if let Some((enc_key, tik_gen)) = self.raw_ticket_keys.get(&rid_hex) {
            if let Some(generation) = nca_key_gen {
                let tkek_name = format!("titlekek_{generation:02x}");
                if let Some(tkek) = self.keys.get(&tkek_name)
                    && tkek.len() == 16
                        && let Ok(cipher) = Aes128::new_from_slice(tkek) {
                            let mut block = *aes::Block::from_slice(enc_key);
                            cipher.decrypt_block(&mut block);
                            let mut res = [0u8; 16];
                            res.copy_from_slice(&block);
                            return Some(res);
                        }
            }

            let tik_name = format!("titlekek_{tik_gen:02x}");
            if let Some(tkek) = self.keys.get(&tik_name)
                && tkek.len() == 16
                    && let Ok(cipher) = Aes128::new_from_slice(tkek) {
                        let mut block = *aes::Block::from_slice(enc_key);
                        cipher.decrypt_block(&mut block);
                        let mut res = [0u8; 16];
                        res.copy_from_slice(&block);
                        return Some(res);
                    }

            return Some(*enc_key);
        }

        None
    }

    pub fn decrypt_ticket_title_key(&mut self, ticket_bytes: &[u8]) -> Option<([u8; 16], [u8; 16])> {
        if ticket_bytes.len() < 0x2B0 {
            return None;
        }

        let mut enc_titlekey = [0u8; 16];
        enc_titlekey.copy_from_slice(&ticket_bytes[0x180..0x190]);

        let key_gen = ticket_bytes[0x285];

        let mut rights_id = [0u8; 16];
        rights_id.copy_from_slice(&ticket_bytes[0x2A0..0x2B0]);
        let rid_hex = hex::encode(rights_id).to_lowercase();

        self.raw_ticket_keys.insert(rid_hex.clone(), (enc_titlekey, key_gen));

        if let Some(cached) = self.title_keys.get(&rid_hex) {
            return Some((rights_id, *cached));
        }

        Some((rights_id, enc_titlekey))
    }
}
