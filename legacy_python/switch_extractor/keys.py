"""
Nintendo Switch Key Management Module
Handles finding, loading, and managing prod.keys and title.keys for decryption.
"""

import os
import re
from pathlib import Path
from typing import Dict, Optional, Tuple
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes


class KeySet:
    """Manages Switch cryptographic keys (prod.keys, title.keys, tickets)."""

    STANDARD_SEARCH_PATHS = [
        # Yuzu standard location
        Path(os.environ.get("APPDATA", "")) / "yuzu" / "keys" / "prod.keys",
        # Ryujinx standard location
        Path(os.environ.get("APPDATA", "")) / "Ryujinx" / "system" / "prod.keys",
        # Switch homebrew standard location
        Path.home() / ".switch" / "prod.keys",
        # Local working directory
        Path("prod.keys"),
        Path("keys.txt"),
        Path("keys.dat"),
    ]

    TITLE_KEYS_SEARCH_PATHS = [
        Path(os.environ.get("APPDATA", "")) / "yuzu" / "keys" / "title.keys",
        Path(os.environ.get("APPDATA", "")) / "Ryujinx" / "system" / "title.keys",
        Path.home() / ".switch" / "title.keys",
        Path("title.keys"),
        Path("title.keys_autogenerated"),
    ]

    def __init__(self, prod_keys_path: Optional[str] = None, title_keys_path: Optional[str] = None):
        self.keys: Dict[str, bytes] = {}
        self.title_keys: Dict[str, bytes] = {}
        self.raw_ticket_keys: Dict[str, Tuple[bytes, int]] = {}
        self.prod_keys_file: Optional[Path] = None
        self.title_keys_file: Optional[Path] = None

        self.load_keys(prod_keys_path, title_keys_path)

    def load_keys(self, prod_keys_path: Optional[str] = None, title_keys_path: Optional[str] = None):
        """Attempts to load keys from provided paths or auto-detect from standard locations."""
        # 1. Load prod.keys
        target_prod = None
        if prod_keys_path and Path(prod_keys_path).is_file():
            target_prod = Path(prod_keys_path)
        else:
            for p in self.STANDARD_SEARCH_PATHS:
                if p and p.is_file():
                    target_prod = p
                    break

        if target_prod and target_prod.is_file():
            self._parse_prod_keys(target_prod)
            self.prod_keys_file = target_prod

        # 2. Load title.keys
        target_title = None
        if title_keys_path and Path(title_keys_path).is_file():
            target_title = Path(title_keys_path)
        else:
            for p in self.TITLE_KEYS_SEARCH_PATHS:
                if p and p.is_file():
                    target_title = p
                    break

        if target_title and target_title.is_file():
            self._parse_title_keys(target_title)
            self.title_keys_file = target_title

    def _parse_prod_keys(self, path: Path):
        """Parses a prod.keys / keys.txt file."""
        try:
            with open(path, "r", encoding="utf-8", errors="ignore") as f:
                for line in f:
                    line = line.strip()
                    if not line or line.startswith("#") or line.startswith(";"):
                        continue
                    if "=" in line:
                        name, val = line.split("=", 1)
                        name = name.strip().lower()
                        val = re.sub(r"[^0-9a-fA-F]", "", val.strip())
                        try:
                            self.keys[name] = bytes.fromhex(val)
                        except ValueError:
                            pass
        except Exception as e:
            print(f"[KeySet] Error reading {path}: {e}")

    def _parse_title_keys(self, path: Path):
        """Parses a title.keys file (rights_id = title_key)."""
        try:
            with open(path, "r", encoding="utf-8", errors="ignore") as f:
                for line in f:
                    line = line.strip()
                    if not line or line.startswith("#") or line.startswith(";"):
                        continue
                    if "=" in line:
                        rights_id, key = line.split("=", 1)
                        rights_id = rights_id.strip().lower()
                        key = re.sub(r"[^0-9a-fA-F]", "", key.strip())
                        try:
                            self.title_keys[rights_id] = bytes.fromhex(key)
                        except ValueError:
                            pass
        except Exception as e:
            print(f"[KeySet] Error reading title.keys {path}: {e}")

    @property
    def has_header_key(self) -> bool:
        return "header_key" in self.keys and len(self.keys["header_key"]) == 32

    def get_header_key(self) -> Optional[bytes]:
        return self.keys.get("header_key")

    def get_key_area_key(self, key_type: str, generation: int) -> Optional[bytes]:
        """
        Retrieves Key Area Key (e.g. key_area_key_application_00).
        key_type is usually 'application', 'ocean', or 'system'.
        """
        name = f"key_area_key_{key_type}_{generation:02x}"
        return self.keys.get(name)

    def decrypt_key_area(self, encrypted_keys: bytes, generation: int, key_type: str = "application") -> list:
        """
        Decrypts NCA key area (4 keys of 16 bytes = 64 bytes total) using AES-ECB.
        Returns list of 4 decrypted 16-byte keys.
        """
        kaek = self.get_key_area_key(key_type, generation)
        if not kaek or len(kaek) != 16:
            return [b"\x00" * 16] * 4

        cipher = Cipher(algorithms.AES(kaek), modes.ECB())
        decryptor = cipher.decryptor()
        decrypted = decryptor.update(encrypted_keys) + decryptor.finalize()

        return [decrypted[i * 16 : (i + 1) * 16] for i in range(4)]

    def get_title_key(self, rights_id: bytes, nca_key_gen: Optional[int] = None) -> Optional[bytes]:
        """
        Looks up title key from loaded title.keys by 16-byte rights_id,
        or decrypts encrypted ticket title key using NCA crypto generation titlekek.
        """
        rid_hex = rights_id.hex().lower()

        # 1. External title.keys file takes precedence (always decrypted)
        if rid_hex in self.title_keys:
            return self.title_keys[rid_hex]

        # 2. Key extracted from ticket (.tik)
        if rid_hex in self.raw_ticket_keys:
            enc_key, tik_gen = self.raw_ticket_keys[rid_hex]
            if nca_key_gen is not None:
                titlekek = self.keys.get(f"titlekek_{nca_key_gen:02x}")
                if titlekek and len(titlekek) == 16:
                    try:
                        cipher = Cipher(algorithms.AES(titlekek), modes.ECB())
                        return cipher.decryptor().update(enc_key)
                    except Exception:
                        pass

            # Fallback to raw key (e.g. cleartext common tickets or when keygen is omitted)
            return enc_key

        return None

    def decrypt_ticket_title_key(self, ticket_bytes: bytes) -> Optional[Tuple[bytes, bytes]]:
        """
        Extracts title key from ticket (.tik).
        Stores raw title key and returns (rights_id, raw_title_key).
        """
        if len(ticket_bytes) < 0x2B0:
            return None

        # Title key block is at offset 0x180 (size 0x100 = 256 bytes)
        tkey_block = ticket_bytes[0x180:0x280]
        # Key generation is at offset 0x285
        key_gen = ticket_bytes[0x285]
        # Rights ID is at offset 0x2A0 (16 bytes)
        rights_id = ticket_bytes[0x2A0:0x2B0]
        rid_hex = rights_id.hex().lower()
        enc_titlekey = tkey_block[:0x10]

        self.raw_ticket_keys[rid_hex] = (enc_titlekey, key_gen)

        return rights_id, enc_titlekey
